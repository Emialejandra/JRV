-- Vincula filas previas por nombre cuando aún no tenían código CNE.
update public.provincias p set cne_codigo=s.provincia_codigo
from (select distinct provincia_codigo, provincia from public.cne_distributivo_2027_import) s
where p.cne_codigo is null
  and regexp_replace(translate(lower(trim(p.nombre)),'áéíóúüñ','aeiouun'),'[^a-z0-9]+','','g')
      = regexp_replace(translate(lower(trim(s.provincia)),'áéíóúüñ','aeiouun'),'[^a-z0-9]+','','g');

insert into public.provincias (nombre,cne_codigo)
select distinct on (provincia_codigo) provincia, provincia_codigo
from public.cne_distributivo_2027_import s
where not exists (select 1 from public.provincias p where p.cne_codigo=s.provincia_codigo)
order by provincia_codigo;

update public.cantones c set cne_codigo=s.canton_codigo
from (select distinct provincia_codigo,canton_codigo,canton from public.cne_distributivo_2027_import) s
join public.provincias p on p.cne_codigo=s.provincia_codigo
where c.provincia_id=p.id and c.cne_codigo is null
  and regexp_replace(translate(lower(trim(c.nombre)),'áéíóúüñ','aeiouun'),'[^a-z0-9]+','','g')
      = regexp_replace(translate(lower(trim(s.canton)),'áéíóúüñ','aeiouun'),'[^a-z0-9]+','','g');

insert into public.cantones (provincia_id,nombre,cne_codigo)
select distinct on (p.id,s.canton_codigo) p.id,s.canton,s.canton_codigo
from public.cne_distributivo_2027_import s
join public.provincias p on p.cne_codigo=s.provincia_codigo
where not exists (select 1 from public.cantones c where c.provincia_id=p.id and c.cne_codigo=s.canton_codigo)
order by p.id,s.canton_codigo;

update public.parroquias pa set cne_codigo=s.parroquia_codigo, tipo=t.tipo
from (select distinct provincia_codigo,canton_codigo,parroquia_codigo,parroquia from public.cne_distributivo_2027_import) s
join public.provincias p on p.cne_codigo=s.provincia_codigo
join public.cantones c on c.provincia_id=p.id and c.cne_codigo=s.canton_codigo
join _cne_parroquia_tipo t using (provincia_codigo,canton_codigo,parroquia_codigo)
where pa.canton_id=c.id and pa.cne_codigo is null
  and regexp_replace(translate(lower(trim(pa.nombre)),'áéíóúüñ','aeiouun'),'[^a-z0-9]+','','g')
      = regexp_replace(translate(lower(trim(s.parroquia)),'áéíóúüñ','aeiouun'),'[^a-z0-9]+','','g');

insert into public.parroquias (canton_id,nombre,cne_codigo,tipo)
select distinct on (c.id,s.parroquia_codigo) c.id,s.parroquia,s.parroquia_codigo,t.tipo
from public.cne_distributivo_2027_import s
join public.provincias p on p.cne_codigo=s.provincia_codigo
join public.cantones c on c.provincia_id=p.id and c.cne_codigo=s.canton_codigo
join _cne_parroquia_tipo t using (provincia_codigo,canton_codigo,parroquia_codigo)
where not exists (select 1 from public.parroquias pa where pa.canton_id=c.id and pa.cne_codigo=s.parroquia_codigo)
order by c.id,s.parroquia_codigo;

-- Conserva el código CNE y los atributos del distributivo en cada recinto.
update public.recintos r set
  direccion=coalesce(nullif(s.direccion,''),r.direccion),
  capacidad_jrv=greatest(coalesce(r.capacidad_jrv,0),s.jrv_total),
  latitud=coalesce(r.latitud,s.latitud), longitud=coalesce(r.longitud,s.longitud),
  cne_zona=s.zona, cne_cda=s.cda,
  juntas_femeninas=s.juntas_femeninas, juntas_masculinas=s.juntas_masculinas,
  electores=s.electores, dificil_acceso=s.dificil_acceso, sin_conectividad=s.sin_conectividad
from public.cne_distributivo_2027_import s
join public.provincias p on p.cne_codigo=s.provincia_codigo
join public.cantones c on c.provincia_id=p.id and c.cne_codigo=s.canton_codigo
join public.parroquias pa on pa.canton_id=c.id and pa.cne_codigo=s.parroquia_codigo
where r.parroquia_id=pa.id and (r.cne_codigo=s.recinto_codigo or
  (r.cne_codigo is null and regexp_replace(translate(lower(trim(r.nombre)),'áéíóúüñ','aeiouun'),'[^a-z0-9]+','','g')
   = regexp_replace(translate(lower(trim(s.recinto)),'áéíóúüñ','aeiouun'),'[^a-z0-9]+','','g')));

