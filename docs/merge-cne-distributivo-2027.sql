 cne_codigo,cne_zona,cne_cda,juntas_femeninas,juntas_masculinas,electores,dificil_acceso,sin_conectividad)
select pa.id,s.recinto,nullif(s.direccion,''),s.jrv_total,s.latitud,s.longitud,true,
 s.recinto_codigo,s.zona,s.cda,s.juntas_femeninas,s.juntas_masculinas,s.electores,s.dificil_acceso,s.sin_conectividad
from public.cne_distributivo_2027_import s
join public.provincias p on p.cne_codigo=s.provincia_codigo
join public.cantones c on c.provincia_id=p.id and c.cne_codigo=s.canton_codigo
join public.parroquias pa on pa.canton_id=c.id and pa.cne_codigo=s.parroquia_codigo
where not exists (select 1 from public.recintos r where r.cne_codigo=s.recinto_codigo);

insert into public.jrv (recinto_id,numero,codigo,tipo,estado)
select r.id,n::integer,concat(s.recinto_codigo,'-',lpad(n::text,3,'0')),'general','pendiente'
from public.cne_distributivo_2027_import s
join public.recintos r on r.cne_codigo=s.recinto_codigo
cross join lateral generate_series(1,s.jrv_total) n
where not exists (select 1 from public.jrv j where j.recinto_id=r.id and j.numero=n);

