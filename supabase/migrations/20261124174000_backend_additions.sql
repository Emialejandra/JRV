create or replace function public.crear_recinto_con_jrv(
  p_parroquia_id bigint,
  p_nombre character varying,
  p_direccion text,
  p_referencia text,
  p_capacidad_jrv integer,
  p_latitud numeric,
  p_longitud numeric
)
returns jsonb
language plpgsql
security definer
set search_path = pg_catalog, public, pg_temp
as $$
declare
  v_actor_id uuid := auth.uid();
  v_role text;
  v_provincia_id bigint;
  v_recinto_id bigint;
  v_capacidad_jrv integer;
  v_recinto_activo boolean;
  v_nombre text := trim(p_nombre);
  v_created boolean := false;
begin
  if v_actor_id is null then
    raise exception using errcode = '42501', message = 'Se requiere una sesión autenticada.';
  end if;

  if v_nombre is null or length(v_nombre) = 0 or length(v_nombre) > 150 then
    raise exception using errcode = '22023', message = 'El nombre del recinto no es válido.';
  end if;

  if p_capacidad_jrv is null or p_capacidad_jrv < 1 or p_capacidad_jrv > 500 then
    raise exception using errcode = '22023', message = 'La cantidad de JRV debe estar entre 1 y 500.';
  end if;

  if p_latitud is not null and (p_latitud < -90 or p_latitud > 90) then
    raise exception using errcode = '22023', message = 'La latitud está fuera de rango.';
  end if;
  if p_longitud is not null and (p_longitud < -180 or p_longitud > 180) then
    raise exception using errcode = '22023', message = 'La longitud está fuera de rango.';
  end if;

  select rol into v_role
  from public.perfiles
  where id = v_actor_id and activo = true;

  if v_role is null or v_role not in ('administrador', 'coordinador_provincial') then
    raise exception using errcode = '42501', message = 'El rol no puede crear recintos.';
  end if;

  select c.provincia_id
    into v_provincia_id
  from public.parroquias p
  join public.cantones c on c.id = p.canton_id
  where p.id = p_parroquia_id;

  if not found then
    raise exception using errcode = '22023', message = 'La parroquia no existe.';
  end if;

  if v_role = 'coordinador_provincial'
    and not exists (
      select 1 from public.asignaciones a
      where a.perfil_id = v_actor_id
        and a.provincia_id = v_provincia_id
        and a.tipo_asignacion = 'coordinador_provincial'
        and a.activo = true
    )
  then
    raise exception using errcode = '42501', message = 'No tienes acceso a esta provincia.';
  end if;

  perform pg_advisory_xact_lock(
    hashtextextended('recinto:' || p_parroquia_id::text || ':' || lower(v_nombre), 0)
  );

  select id, activo into v_recinto_id, v_recinto_activo
  from public.recintos
  where parroquia_id = p_parroquia_id
    and lower(trim(nombre)) = lower(v_nombre)
  limit 1
  for update;

  if v_recinto_id is null then
    insert into public.recintos (
      parroquia_id,
      nombre,
      direccion,
      referencia,
      capacidad_jrv,
      latitud,
      longitud,
      activo
    )
    values (
      p_parroquia_id,
      v_nombre,
      nullif(trim(p_direccion), ''),
      nullif(trim(p_referencia), ''),
      p_capacidad_jrv,
      p_latitud,
      p_longitud,
      true
    )
    returning id into v_recinto_id;

    v_created := true;
  else
    if not v_recinto_activo then
      raise exception using
        errcode = '23505',
        message = 'Ya existe un recinto inactivo con ese nombre en la parroquia.';
    end if;

    update public.recintos
    set capacidad_jrv = greatest(coalesce(capacidad_jrv, 0), p_capacidad_jrv),
        latitud = coalesce(p_latitud, latitud),
        longitud = coalesce(p_longitud, longitud)
    where id = v_recinto_id;
  end if;

  select capacidad_jrv into v_capacidad_jrv
  from public.recintos
  where id = v_recinto_id;

  insert into public.jrv (recinto_id, numero, tipo, estado)
  select v_recinto_id, series.numero, 'general', 'pendiente'
  from generate_series(1, v_capacidad_jrv) as series(numero)
  on conflict (recinto_id, numero) do nothing;

  return jsonb_build_object(
    'id', v_recinto_id,
    'recinto_id', v_recinto_id,
    'provincia_id', v_provincia_id,
    'parroquia_id', p_parroquia_id,
    'nombre', v_nombre,
    'capacidad_jrv', v_capacidad_jrv,
    'created', v_created
  );
end;
$$;

