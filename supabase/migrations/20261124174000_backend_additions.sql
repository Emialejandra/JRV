create or replace function public.guardar_acta_electoral(
  p_acta_id bigint,
  p_jrv_id bigint,
  p_dignidad character varying,
  p_votos jsonb,
  p_total_votos_blancos integer,
  p_total_votos_nulos integer,
  p_total_votantes integer,
  p_client_id uuid,
  p_expected_updated_at timestamp with time zone,
  p_latitud numeric,
  p_longitud numeric,
  p_fotografia_path text,
  p_observaciones text
)
returns jsonb
language plpgsql
security definer
set search_path = pg_catalog, public, pg_temp
as $$
declare
  v_actor_id uuid := auth.uid();
  v_role text;
  v_recinto_id bigint;
  v_provincia_id bigint;
  v_acta public.actas%rowtype;
  v_client_id uuid := p_client_id;
  v_total_votos_validos bigint;
  v_cantidad_votos bigint;
  v_candidaturas_distintas bigint;
  v_organizaciones_distintas bigint;
  v_candidaturas_invalidas bigint;
  v_before jsonb;
  v_after jsonb;
  v_created boolean := false;
begin
  if v_actor_id is null then
    raise exception using
      errcode = '42501',
      message = 'Se requiere una sesión autenticada.';
  end if;

  if p_dignidad is null or p_dignidad not in ('alcaldia', 'prefectura') then
    raise exception using
      errcode = '22023',
      message = 'La dignidad debe ser alcaldia o prefectura.';
  end if;

  if coalesce(jsonb_typeof(p_votos), '') <> 'array'
    or jsonb_array_length(p_votos) <> 5
  then
    raise exception using
      errcode = '22023',
      message = 'El acta debe contener exactamente cinco candidaturas.';
  end if;

  if exists (
    select 1
    from jsonb_array_elements(p_votos) as vote(value)
    where case
      when jsonb_typeof(value->'candidatura_id') = 'number'
        and value->>'candidatura_id' ~ '^[1-9][0-9]*$'
        then (value->>'candidatura_id')::numeric > 9223372036854775807
      else true
    end
      or case
        when jsonb_typeof(value->'cantidad_votos') = 'number'
          and value->>'cantidad_votos' ~ '^[0-9]+$'
          then (value->>'cantidad_votos')::numeric > 2147483647
        else true
      end
  ) then
    raise exception using
      errcode = '22023',
      message = 'Cada voto debe incluir una candidatura y una cantidad entera no negativa dentro de rango.';
  end if;

  if coalesce(p_total_votos_blancos, -1) < 0
    or coalesce(p_total_votos_nulos, -1) < 0
    or coalesce(p_total_votantes, -1) < 0
  then
    raise exception using
      errcode = '22023',
      message = 'Los totales deben ser enteros no negativos.';
  end if;

  if p_acta_id is null and p_client_id is null then
    raise exception using
      errcode = '22023',
      message = 'client_id es obligatorio para registrar un acta.';
  end if;

  if p_acta_id is null and p_fotografia_path is null then
    raise exception using
      errcode = '22023',
      message = 'La fotografía del acta es obligatoria.';
  end if;

  if p_latitud is not null and (p_latitud < -90 or p_latitud > 90) then
    raise exception using
      errcode = '22023',
      message = 'La latitud está fuera de rango.';
  end if;

  if p_longitud is not null and (p_longitud < -180 or p_longitud > 180) then
    raise exception using
      errcode = '22023',
      message = 'La longitud está fuera de rango.';
  end if;

  select p.rol
    into v_role
  from public.perfiles p
  where p.id = v_actor_id
    and p.activo = true;

  if not found then
    raise exception using
      errcode = '42501',
      message = 'El perfil no existe o está inactivo.';
  end if;

  select r.id, c.provincia_id
    into v_recinto_id, v_provincia_id
  from public.jrv j
  join public.recintos r on r.id = j.recinto_id
  join public.parroquias pa on pa.id = r.parroquia_id
  join public.cantones c on c.id = pa.canton_id
  where j.id = p_jrv_id;

  if not found then
    raise exception using
      errcode = '22023',
      message = 'La JRV no existe o no tiene una jerarquía territorial completa.';
  end if;

  if v_role = 'veedor' then
    if not exists (
      select 1 from public.asignaciones a
      where a.perfil_id = v_actor_id
        and a.jrv_id = p_jrv_id
        and a.tipo_asignacion = 'veedor'
        and a.activo = true
    ) then
      raise exception using
        errcode = '42501',
        message = 'El veedor no tiene asignada esta JRV.';
    end if;
  elsif v_role = 'coordinador_recinto' then
    if not exists (
      select 1 from public.asignaciones a
      where a.perfil_id = v_actor_id
        and a.recinto_id = v_recinto_id
        and a.tipo_asignacion = 'coordinador_recinto'
        and a.activo = true
    ) then
      raise exception using
        errcode = '42501',
        message = 'El coordinador no pertenece a este recinto.';
    end if;
  elsif v_role = 'coordinador_provincial' then
    if not exists (
      select 1 from public.asignaciones a
      where a.perfil_id = v_actor_id
        and a.provincia_id = v_provincia_id
        and a.tipo_asignacion = 'coordinador_provincial'
        and a.activo = true
    ) then
      raise exception using
        errcode = '42501',
        message = 'El coordinador no pertenece a esta provincia.';
    end if;
  elsif v_role <> 'administrador' then
    raise exception using
      errcode = '42501',
      message = 'El rol no puede acceder a actas.';
  end if;

  select
    count(*),
    count(distinct v.candidatura_id),
    count(distinct c.organizacion_id),
    coalesce(sum(v.cantidad_votos), 0),
    count(*) filter (
      where v.candidatura_id is null
        or v.cantidad_votos is null
        or v.cantidad_votos < 0
        or c.id is null
        or c.dignidad <> p_dignidad
        or c.activo is not true
        or o.activo is not true
    )
  into
    v_cantidad_votos,
    v_candidaturas_distintas,
    v_organizaciones_distintas,
    v_total_votos_validos,
    v_candidaturas_invalidas
  from jsonb_to_recordset(p_votos) as v(
    candidatura_id bigint,
    cantidad_votos integer
  )
  left join public.candidaturas c on c.id = v.candidatura_id
  left join public.organizaciones o on o.id = c.organizacion_id;

  if v_cantidad_votos <> 5
    or v_candidaturas_distintas <> 5
    or v_organizaciones_distintas <> 5
    or v_candidaturas_invalidas <> 0
  then
    raise exception using
      errcode = '22023',
      message = 'Las cinco candidaturas deben ser distintas, activas, corresponder a la dignidad y a organizaciones activas diferentes.';
  end if;

  if v_total_votos_validos + p_total_votos_blancos + p_total_votos_nulos
    <> p_total_votantes
  then
    raise exception using
      errcode = '22023',
      message = 'La suma de votos válidos, blancos y nulos debe coincidir con el total de sufragantes.';
  end if;

  if v_total_votos_validos > 2147483647 then
    raise exception using
      errcode = '22023',
      message = 'La suma de votos válidos supera el límite permitido.';
  end if;

  if p_fotografia_path is not null
    and p_fotografia_path not like
      format('jrv/%s/%s/%s/%%', p_jrv_id, p_dignidad, v_actor_id)
  then
    raise exception using
      errcode = '42501',
      message = 'La fotografía no pertenece a esta JRV, dignidad y usuario.';
  end if;

  if p_fotografia_path is not null
    and not exists (
      select 1
      from storage.objects so
      where so.bucket_id = 'actas-electorales'
        and so.name = p_fotografia_path
    )
  then
    raise exception using
      errcode = '22023',
      message = 'La fotografía no existe en el almacenamiento privado.';
  end if;

  if p_acta_id is null and p_client_id is not null then
    select jsonb_build_object(
      'acta', to_jsonb(a),
      'votos', coalesce(
        (
          select jsonb_agg(to_jsonb(d) order by d.candidatura_id)
          from public.detalle_votos d
          where d.acta_id = a.id
        ),
        '[]'::jsonb
      )
    )
      into v_after
    from public.actas a
    where a.registrado_por = v_actor_id
      and a.client_id = p_client_id
      and a.jrv_id = p_jrv_id
      and a.dignidad = p_dignidad;

    if found then
      return jsonb_build_object(
        'acta', v_after,
        'created', false,
        'duplicate', true
      );
    end if;
  end if;

  if p_acta_id is not null then
    select a.*
      into v_acta
    from public.actas a
    where a.id = p_acta_id
    for update;

    if not found then
      raise exception using
        errcode = 'P0002',
        message = 'El acta no existe.';
    end if;

    if v_acta.jrv_id <> p_jrv_id or v_acta.dignidad <> p_dignidad then
      raise exception using
        errcode = '22023',
        message = 'La JRV y dignidad no coinciden con el acta seleccionada.';
    end if;

    if v_acta.estado not in ('registrada', 'observada', 'rechazada') then
      raise exception using
        errcode = '55000',
        message = 'El acta ya no admite correcciones.';
    end if;

    if p_fotografia_path is null and v_acta.fotografia_path is null then
      raise exception using
        errcode = '22023',
        message = 'Debes adjuntar una fotografía antes de corregir esta acta.';
    end if;

    if p_expected_updated_at is null
      or v_acta.updated_at is distinct from p_expected_updated_at
    then
      raise exception using
        errcode = '40001',
        message = 'El acta cambió desde la última sincronización. Recarga antes de corregir.';
    end if;

    if v_role = 'veedor' and v_acta.registrado_por <> v_actor_id then
      raise exception using
        errcode = '42501',
        message = 'Un veedor solo puede corregir sus propias actas.';
    end if;

    if v_role = 'coordinador_provincial' then
      raise exception using
        errcode = '42501',
        message = 'El coordinador provincial no puede corregir actas.';
    end if;

    v_before := jsonb_build_object(
      'acta', to_jsonb(v_acta),
      'votos', coalesce(
        (
          select jsonb_agg(to_jsonb(d))
          from public.detalle_votos d
          where d.acta_id = v_acta.id
        ),
        '[]'::jsonb
      )
    );

    update public.actas
    set total_votos_validos = v_total_votos_validos,
        total_votos_blancos = p_total_votos_blancos,
        total_votos_nulos = p_total_votos_nulos,
        total_votantes = p_total_votantes,
        dignidad = p_dignidad,
        latitud = p_latitud,
        longitud = p_longitud,
        fotografia_path = coalesce(p_fotografia_path, fotografia_path),
        observaciones = p_observaciones,
        estado = 'registrada',
        client_id = coalesce(p_client_id, client_id),
        updated_at = now()
    where id = p_acta_id
    returning * into v_acta;
  else
    if v_role <> 'veedor' then
      raise exception using
        errcode = '42501',
        message = 'Solo un veedor asignado puede crear un acta.';
    end if;

    insert into public.actas (
      jrv_id,
      registrado_por,
      fotografia_url,
      fecha_registro,
      latitud,
      longitud,
      total_votos_validos,
      total_votos_blancos,
      total_votos_nulos,
      total_votantes,
      observaciones,
      estado,
      dignidad,
      client_id,
      fotografia_path
    )
    values (
      p_jrv_id,
      v_actor_id,
      null,
      now(),
      p_latitud,
      p_longitud,
      v_total_votos_validos,
      p_total_votos_blancos,
      p_total_votos_nulos,
      p_total_votantes,
      p_observaciones,
      'registrada',
      p_dignidad,
      v_client_id,
      p_fotografia_path
    )
    returning * into v_acta;

    v_created := true;
  end if;

  delete from public.detalle_votos
  where acta_id = v_acta.id;

  insert into public.detalle_votos (acta_id, candidatura_id, cantidad_votos)
  select
    v_acta.id,
    v.candidatura_id,
    v.cantidad_votos
  from jsonb_to_recordset(p_votos) as v(
    candidatura_id bigint,
    cantidad_votos integer
  );

  select jsonb_build_object(
    'acta', to_jsonb(a),
    'votos', coalesce(
      (
        select jsonb_agg(to_jsonb(d) order by d.candidatura_id)
        from public.detalle_votos d
        where d.acta_id = a.id
      ),
      '[]'::jsonb
    )
  )
  into v_after
  from public.actas a
  where a.id = v_acta.id;

  if not v_created then
    insert into public.historial_actas (
      acta_id,
      actor_id,
      accion,
      antes,
      despues
    )
    values (
      v_acta.id,
      v_actor_id,
      'correccion',
      v_before,
      v_after
    );
  end if;

  return jsonb_build_object(
    'acta', v_after,
    'created', v_created,
    'duplicate', false
  );
end;
$$;

