create or replace function public.asignar_veedor_jrv(
  p_veedor_id uuid,
  p_jrv_id bigint
)
returns jsonb
language plpgsql
security definer
set search_path = pg_catalog, public, pg_temp
as $$
declare
  v_actor_id uuid := auth.uid();
  v_actor_role text;
  v_veedor_id uuid;
  v_recinto_id bigint;
  v_asignacion_id bigint;
begin
  if v_actor_id is null then
    raise exception using errcode = '42501', message = 'Se requiere una sesión autenticada.';
  end if;

  select rol into v_actor_role
  from public.perfiles
  where id = v_actor_id and activo = true;

  if v_actor_role is null
    or v_actor_role not in ('administrador', 'coordinador_recinto')
  then
    raise exception using errcode = '42501', message = 'El rol no puede asignar veedores.';
  end if;

  select id into v_veedor_id
  from public.perfiles
  where id = p_veedor_id and rol = 'veedor' and activo = true
  for update;

  if not found then
    raise exception using errcode = '22023', message = 'El veedor no existe o está inactivo.';
  end if;

  select recinto_id into v_recinto_id
  from public.jrv
  where id = p_jrv_id
  for update;

  if not found then
    raise exception using errcode = 'P0002', message = 'La JRV no existe.';
  end if;

  if v_actor_role = 'coordinador_recinto' then
    if not exists (
      select 1 from public.asignaciones
      where perfil_id = v_actor_id
        and recinto_id = v_recinto_id
        and tipo_asignacion = 'coordinador_recinto'
        and activo = true
    ) then
      raise exception using errcode = '42501', message = 'No tienes acceso a este recinto.';
    end if;

    if exists (
      select 1 from public.asignaciones
      where perfil_id = v_veedor_id
        and tipo_asignacion = 'veedor'
        and activo = true
        and recinto_id is distinct from v_recinto_id
    ) then
      raise exception using errcode = '42501', message = 'El veedor está asignado a otro recinto.';
    end if;
  end if;

  update public.asignaciones
  set activo = false,
      updated_at = now()
  where tipo_asignacion = 'veedor'
    and activo = true
    and perfil_id = v_veedor_id;

  insert into public.asignaciones (
    perfil_id,
    jrv_id,
    recinto_id,
    tipo_asignacion,
    fecha_asignacion,
    activo
  )
  values (
    v_veedor_id,
    p_jrv_id,
    v_recinto_id,
    'veedor',
    now(),
    true
  )
  returning id into v_asignacion_id;

  return jsonb_build_object(
    'id', v_asignacion_id,
    'perfil_id', v_veedor_id,
    'jrv_id', p_jrv_id,
    'recinto_id', v_recinto_id,
    'activo', true
  );
end;
$$;

revoke all on function public.asignar_veedor_jrv(uuid, bigint)
  from public, anon;
grant execute on function public.asignar_veedor_jrv(uuid, bigint)
  to authenticated;

