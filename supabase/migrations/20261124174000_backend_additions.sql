create or replace function public.precargar_datos_electorales(
  p_actor_id uuid,
  p_provincia_id bigint,
  p_canton_id bigint,
  p_organizaciones jsonb,
  p_candidaturas jsonb,
  p_recintos jsonb
)
returns jsonb
language plpgsql
security definer
set search_path = pg_catalog, public, pg_temp
as $$
declare
  v_organizacion jsonb;
  v_candidatura jsonb;
  v_recinto jsonb;
  v_organizacion_id bigint;
  v_recinto_id bigint;
  v_recinto_activo boolean;
  v_parroquia_id bigint;
  v_cantidad_jrv integer;
  v_capacidad_actual integer;
  v_indice integer;
  v_organizaciones integer;
  v_candidaturas_alcaldia integer;
  v_candidaturas_prefectura integer;
  v_recintos integer;
  v_insertadas integer := 0;
  v_resultados jsonb := '[]'::jsonb;
begin
  if not exists (
    select 1 from public.perfiles
    where id = p_actor_id
      and rol = 'administrador'
      and activo = true
  ) then
    raise exception using errcode = '42501', message = 'Solo un administrador activo puede precargar datos.';
  end if;

  if coalesce(jsonb_typeof(p_organizaciones), '') <> 'array'
    or coalesce(jsonb_typeof(p_candidaturas), '') <> 'array'
    or coalesce(jsonb_typeof(p_recintos), '') <> 'array'
  then
    raise exception using errcode = '22023', message = 'Organizaciones, candidaturas y recintos deben ser arreglos.';
  end if;

  select count(*) into v_organizaciones
  from jsonb_array_elements(p_organizaciones);
  select count(*) into v_candidaturas_alcaldia
  from jsonb_array_elements(p_candidaturas) c
  where c->>'dignidad' = 'alcaldia';
  select count(*) into v_candidaturas_prefectura
  from jsonb_array_elements(p_candidaturas) c
  where c->>'dignidad' = 'prefectura';
  select count(*) into v_recintos
  from jsonb_array_elements(p_recintos);

  if v_organizaciones <> 5
    or v_candidaturas_alcaldia <> 5
    or v_candidaturas_prefectura <> 5
    or v_recintos < 1
    or (
      select count(distinct lower(trim(o->>'nombre')))
      from jsonb_array_elements(p_organizaciones) o
    ) <> 5
    or (
      select count(distinct concat_ws(
        '|',
        c->>'dignidad',
        lower(trim(c->>'nombres')),
        lower(trim(c->>'apellidos'))
      ))
      from jsonb_array_elements(p_candidaturas) c
    ) <> 10
    or (
      select count(distinct c->>'organizacion')
      from jsonb_array_elements(p_candidaturas) c
      where c->>'dignidad' = 'alcaldia'
    ) <> 5
    or (
      select count(distinct c->>'organizacion')
      from jsonb_array_elements(p_candidaturas) c
      where c->>'dignidad' = 'prefectura'
    ) <> 5
  then
    raise exception using errcode = '22023', message = 'Se requieren cinco organizaciones y cinco candidaturas por dignidad.';
  end if;

  if exists (
    select 1
    from jsonb_array_elements(p_recintos) as item(value)
    where case
      when jsonb_typeof(value->'parroquia_id') = 'number'
        and value->>'parroquia_id' ~ '^[1-9][0-9]*$'
        then (value->>'parroquia_id')::numeric > 9223372036854775807
      else true
    end
      or case
        when jsonb_typeof(value->'cantidad_jrv') = 'number'
          and value->>'cantidad_jrv' ~ '^[0-9]+$'
          then (value->>'cantidad_jrv')::numeric < 1
            or (value->>'cantidad_jrv')::numeric > 500
        else true
      end
  ) then
    raise exception using
      errcode = '22023',
      message = 'Cada recinto debe incluir parroquia_id y cantidad_jrv válidos.';
  end if;

  if not exists (
    select 1 from public.cantones c
    where c.id = p_canton_id
      and c.provincia_id = p_provincia_id
  ) then
    raise exception using errcode = '22023', message = 'El cantón no pertenece a la provincia indicada.';
  end if;

  perform pg_advisory_xact_lock(hashtextextended('precarga-electoral', 0));

  for v_organizacion in select value from jsonb_array_elements(p_organizaciones)
  loop
    if coalesce(length(trim(v_organizacion->>'nombre')), 0) = 0
      or length(trim(v_organizacion->>'nombre')) > 150
      or coalesce(length(trim(v_organizacion->>'sigla')), 0) > 30
      or coalesce(length(trim(v_organizacion->>'numero_lista')), 0) > 20
    then
      raise exception using errcode = '22023', message = 'Cada organización requiere un nombre.';
    end if;

    insert into public.organizaciones (nombre, sigla, numero_lista, activo)
    select
      trim(v_organizacion->>'nombre'),
      nullif(trim(v_organizacion->>'sigla'), ''),
      nullif(trim(v_organizacion->>'numero_lista'), ''),
      true
    where not exists (
      select 1
      from public.organizaciones o
      where lower(trim(o.nombre)) = lower(trim(v_organizacion->>'nombre'))
    );
  end loop;

  for v_candidatura in select value from jsonb_array_elements(p_candidaturas)
  loop
    select o.id into v_organizacion_id
    from public.organizaciones o
    where lower(trim(o.nombre)) = lower(trim(v_candidatura->>'organizacion'));

    if v_organizacion_id is null
      or not exists (
        select 1
        from jsonb_array_elements(p_organizaciones) o
        where lower(trim(o->>'nombre')) = lower(trim(v_candidatura->>'organizacion'))
      )
      or v_candidatura->>'dignidad' is null
      or v_candidatura->>'dignidad' not in ('alcaldia', 'prefectura')
      or coalesce(length(trim(v_candidatura->>'nombres')), 0) = 0
      or length(trim(v_candidatura->>'nombres')) > 100
      or coalesce(length(trim(v_candidatura->>'apellidos')), 0) = 0
      or length(trim(v_candidatura->>'apellidos')) > 100
      or coalesce(length(trim(v_candidatura->>'numero_lista')), 0) > 20
    then
      raise exception using errcode = '22023', message = 'Una candidatura contiene datos inválidos o una organización desconocida.';
    end if;

    insert into public.candidaturas (
      organizacion_id,
      nombres,
      apellidos,
      dignidad,
      numero_lista,
      activo
    )
    select
      v_organizacion_id,
      trim(v_candidatura->>'nombres'),
      trim(v_candidatura->>'apellidos'),
      v_candidatura->>'dignidad',
      nullif(trim(v_candidatura->>'numero_lista'), ''),
      true
    where not exists (
      select 1 from public.candidaturas c
      where c.organizacion_id = v_organizacion_id
        and c.dignidad = v_candidatura->>'dignidad'
        and lower(c.nombres) = lower(trim(v_candidatura->>'nombres'))
        and lower(c.apellidos) = lower(trim(v_candidatura->>'apellidos'))
    );
    get diagnostics v_indice = row_count;
    v_insertadas := v_insertadas + v_indice;
  end loop;

  for v_recinto in select value from jsonb_array_elements(p_recintos)
  loop
    v_parroquia_id := (v_recinto->>'parroquia_id')::bigint;
    v_cantidad_jrv := (v_recinto->>'cantidad_jrv')::integer;

    if v_cantidad_jrv is null or v_cantidad_jrv < 1 or v_cantidad_jrv > 500 then
      raise exception using errcode = '22023', message = 'cantidad_jrv debe estar entre 1 y 500.';
    end if;

    if coalesce(length(trim(v_recinto->>'nombre')), 0) = 0
      or length(trim(v_recinto->>'nombre')) > 150
    then
      raise exception using errcode = '22023', message = 'Cada recinto requiere un nombre válido.';
    end if;

    if not exists (
      select 1 from public.parroquias p
      where p.id = v_parroquia_id
        and p.canton_id = p_canton_id
    ) then
      raise exception using errcode = '22023', message = 'La parroquia de un recinto no pertenece al cantón seleccionado.';
    end if;

    select r.id, r.activo into v_recinto_id, v_recinto_activo
    from public.recintos r
    where r.parroquia_id = v_parroquia_id
      and lower(trim(r.nombre)) = lower(trim(v_recinto->>'nombre'))
    limit 1;

    if v_recinto_id is null then
      insert into public.recintos (
        parroquia_id,
        nombre,
        direccion,
        referencia,
        capacidad_jrv,
        activo
      )
      values (
        v_parroquia_id,
        trim(v_recinto->>'nombre'),
        nullif(trim(v_recinto->>'direccion'), ''),
        nullif(trim(v_recinto->>'referencia'), ''),
        v_cantidad_jrv,
        true
      )
      returning id into v_recinto_id;
    else
      if not v_recinto_activo then
        raise exception using
          errcode = '23505',
          message = 'Ya existe un recinto inactivo con ese nombre en la parroquia.';
      end if;

      update public.recintos
      set capacidad_jrv = greatest(coalesce(capacidad_jrv, 0), v_cantidad_jrv)
      where id = v_recinto_id;
    end if;

    select capacidad_jrv into v_capacidad_actual
    from public.recintos
    where id = v_recinto_id;

    insert into public.jrv (recinto_id, numero, tipo, estado)
    select v_recinto_id, series.numero, 'general', 'pendiente'
    from generate_series(1, v_capacidad_actual) as series(numero)
    on conflict (recinto_id, numero) do nothing;

    v_resultados := v_resultados || jsonb_build_array(
      jsonb_build_object(
        'recinto_id', v_recinto_id,
        'nombre', trim(v_recinto->>'nombre'),
        'cantidad_jrv', v_capacidad_actual
      )
    );
  end loop;

  return jsonb_build_object(
    'provincia_id', p_provincia_id,
    'canton_id', p_canton_id,
    'organizaciones', v_organizaciones,
    'candidaturas_alcaldia', v_candidaturas_alcaldia,
    'candidaturas_prefectura', v_candidaturas_prefectura,
    'candidaturas_insertadas', v_insertadas,
    'recintos', v_resultados
  );
end;
$$;

